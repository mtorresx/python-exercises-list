#Este código pede um número para o usuário
#Depois calcula o dobro, o triplo e a metade desse número
#E mostra todos os resultados na tela

valor = int(input("Digite um número inteiro: "))

dobro = valor * 2
triplo = valor * 3
metade = valor / 2

print(f"O número digitado foi {valor}")
print(f"O dobro é {dobro}")
print(f"O triplo é {triplo}")
print(f"A metade é {metade}")